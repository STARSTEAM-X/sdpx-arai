const auth = (token: string) => ({ headers: { authorization: `Bearer ${token}` } })
if (new URL(process.env.API_BASE_URL!).hostname !== 'api-test') throw new Error('Implementation tests require the disposable api-test stack')

async function prepare(api: APIRequestContext, owner: string, classroomId: string, deadline = '2099-01-01T00:00:00Z', groupCount = 3) {
  // Guard the disposable test environment before any seed fixture touches it.
  expect(new URL(process.env.API_BASE_URL!).hostname).toBe('api-test')
  const csv = ['email,group_name', ...Array.from({ length: groupCount * 4 }, (_, i) => `implementation${i}@kmitl.ac.th,กลุ่ม-${Math.floor(i / 4) + 1}`)].join('\n')
  expect((await api.post(`/api/classrooms/${classroomId}/roster:import`, { ...auth(owner), multipart: { file: { name: 'implementation.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) } } })).status()).toBe(200)
  const created = await api.post('/api/assignments', { ...auth(owner), data: {
    classroomId, name: 'งานตรวจสอบหลังแก้ไข', groupMaxScore: 15, individualMaxScore: 5,
    groupDeadlineUtc: deadline, individualDeadlineUtc: deadline, targetCoverage: 2,
    criteria: [{ side: 'GROUP', name: 'ประสบการณ์การใช้งาน', weightPct: 100, question: 'ผลงานของกลุ่มใดใช้งานได้ดีกว่า?' }, { side: 'INDIVIDUAL', name: 'การมีส่วนร่วม', weightPct: 100 }],
  } })
  expect(created.status()).toBe(201)
  const id = (await created.json()).id as string
  expect((await api.post(`/api/assignments/${id}:publish`, auth(owner))).status()).toBe(200)
  const token = await issueToken(api, 'implementation0@kmitl.ac.th')
  return { id, token }
}
async function login(page: Page, token: string, guestHome = false) {
  await page.addInitScript(({ value, guestHome }) => {
    if (!guestHome || location.pathname !== '/') localStorage.setItem('paireval.session', value)
  }, { value: token, guestHome })
}
async function pairs(api: APIRequestContext, id: string, token: string) {
  const response = await api.get(`/api/assignments/${id}/my-evaluations?side=GROUP`, auth(token))
  expect(response.status()).toBe(200)
  return response.json()
}

